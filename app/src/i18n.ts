const SPACES = "[ " + String.fromCharCode(0xa0) + NNBSP + "]+";
const BEFORE_MARK = new RegExp(SPACES + "([:;!?%»])", "g");
const AFTER_OPENING_QUOTE = new RegExp("«" + SPACES, "g");

/** French typography: a narrow no-break space before « : ; ! ? % » and inside « », so a narrow panel never breaks a
 * line before them, and the typographic apostrophe (’). Only in French (English has no such spaces). Ordinals
 * (« 1er », « 2e ») get their raised suffix later, once escaped (render/html.ts `ordinals`). */
export function frenchSpaces(text: string): string {
  if (lang !== "fr") return text;
  return text.replace(BEFORE_MARK, NNBSP + "$1").replace(AFTER_OPENING_QUOTE, "«" + NNBSP).replace(/'/g, "’");
}

/** The text of `key` in the current language, `{name}` replaced by `vars.name` (unknown names are left as they are). */
export function t(key: Key, vars?: Record<string, string | number>): string {
  const mac = `${key}.mac`;
  if (platform === "macos" && mac in fr) key = mac as Key;
  const text = DICTIONARIES[lang][key] ?? fr[key] ?? key;
  return frenchSpaces(vars ? text.replace(/\{(\w+)\}/g, (all, name: string) => (name in vars ? String(vars[name]) : all)) : text);
}

/** Fills the static texts of a page: `data-i18n` (text), `data-i18n-placeholder`, `data-i18n-title`, `data-i18n-aria`
 * (aria-label). On a whole document it also sets `<html lang>`. */
export function applyI18n(root: ParentNode): void {
  const each = (attr: string, set: (el: HTMLElement, text: string) => void) =>
    root.querySelectorAll<HTMLElement>(`[${attr}]`).forEach((el) => set(el, t(el.getAttribute(attr) as Key)));
  each("data-i18n", (el, text) => (el.textContent = text));
  each("data-i18n-placeholder", (el, text) => el.setAttribute("placeholder", text));
  each("data-i18n-title", (el, text) => el.setAttribute("title", text));
  each("data-i18n-aria", (el, text) => el.setAttribute("aria-label", text));
  if ("documentElement" in root) (root as Document).documentElement.lang = lang;
}
